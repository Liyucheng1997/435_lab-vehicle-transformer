/* ---------------- 手（+x 侧，掌心朝向身体） ---------------- */
function buildHand(M) {
  const b = new Builder();
  // 先按“手指沿 x 排开、向 +z 弯曲”建，再整体转向
  b.with(X(0, 0, 0, 0, -PI / 2, 0), (b) => {
    b.box(0.2, 0.2, 0.075, M.gun, X(0, -0.14, 0), 0.02);
    b.add(plate(symPts([[0, -0.23], [0.09, -0.21], [0.1, -0.06], [0, -0.04]]), 0.03, 0.008), M.paint, X(0, 0, -0.045));
    const finger = (x, len, curl) => {
      let m = X(x, -0.24, 0, curl[0], 0, 0);
      const seg = [0.095 * len, 0.075 * len, 0.06 * len];
      for (let i = 0; i < 3; i++) {
        b.with(m, (b) => {
          b.add(cyl(0.024, 0.046, 'x', 12), M.steel);
          b.box(0.042, seg[i], 0.04, i === 0 ? M.gun : M.dark, X(0, -seg[i] / 2, 0), 0.01);
        });
        m = m.clone().multiply(X(0, -seg[i], 0, curl[i + 1] || 0, 0, 0));
      }
    };
    finger(-0.076, 0.95, [0.2, 0.5, 0.4]);
    finger(-0.026, 1.05, [0.25, 0.55, 0.45]);
    finger(0.026, 1.0, [0.3, 0.6, 0.45]);
    finger(0.076, 0.85, [0.38, 0.65, 0.5]);
    // 拇指
    b.with(X(-0.105, -0.1, 0.02, 0.5, 0, 0.9), (b) => {
      b.add(cyl(0.026, 0.05, 'x', 12), M.steel);
      b.box(0.046, 0.09, 0.044, M.gun, X(0, -0.045, 0), 0.01);
      b.box(0.042, 0.07, 0.04, M.dark, X(0, -0.125, 0.012, 0.4, 0, 0), 0.01);
    });
  });
  return b;
}

export function buildMech(M) {
  const mirror = new THREE.Matrix4().makeScale(-1, 1, 1);
  const pair = (name, b) => ({
    L: b.build(name + '_L'),
    R: new Builder().merge(b, mirror).build(name + '_R'),
  });
  return {
    head: buildHead(M).build('head'),
    chest: buildChest(M).build('chest'),
    abdomen: buildAbdomen(M).build('abdomen'),
    pelvis: buildPelvis(M).build('pelvis'),
    thigh: pair('thigh', buildThigh(M)),
    foot: pair('foot', buildFoot(M)),
    shoulder: pair('shoulder', buildShoulder(M)),
    upperArm: pair('upperArm', buildUpperArm(M)),
    forearm: pair('forearm', buildForearm(M)),
    hand: pair('hand', buildHand(M)),
  };
}
